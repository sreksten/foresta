package com.threeamigos.foresta.tipi;

/**
 * Se un incantesimo fa bene o male al bersaglio. (Da non confondere con {@link ClasseIncantesimo}, che li identifica uno per uno.)
 */
public enum TipoIncantesimo {

	/**
	 * Indica che l'incantesimo apporta benefici al bersaglio
	 */
	BENEFICO,

	/**
	 * Indica che l'incantesimo apporta danni al bersaglio
	 */
	MALEFICO
	
}
