package com.threeamigos.foresta.tipi;

/**
 * Indica se un incantesimo fa bene o male al bersaglio. (Da non confondere con {@link TipoIncantesimo},
 * che li identifica uno per uno.)
 *
 * @author Stefano Reksten
 */
public enum CategoriaIncantesimo {

	/**
	 * Indica che l'incantesimo apporta benefici al bersaglio
	 */
	BENEFICO,

	/**
	 * Indica che l'incantesimo apporta danni al bersaglio
	 */
	MALEFICO
	
}
